import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { prisma } from "@/lib/db";
import { requireAdmin } from "@/lib/auth/session";
import { isDemoMode } from "@/lib/env";
import { Alert, PageHeader, StatCard } from "@/components/ui/primitives";
import { DemoControlPanel } from "@/components/demo/DemoControlPanel";
import { demoSimSettings, DEMO_PRESETS } from "@/lib/demo/settings";
import { SCENARIOS } from "@/lib/demo/engine";
import { DEMO_ACCOUNTS } from "@/lib/demo/catalog";
import { formatMoney } from "@/lib/money";

export const metadata: Metadata = { title: "Demo control center" };
// A full reset rebuilds the baseline through the real pipeline.
export const maxDuration = 300;

export default async function DemoControlCenter() {
  if (!isDemoMode()) notFound();
  await requireAdmin("settings:manage");
  const demo = { isDemo: true };
  const [settings, rfqs, simulated, sellers, buyers, unlocks, quotes, selected, claims, unlockSum, version] = await Promise.all([
    demoSimSettings(),
    prisma.rfq.count({ where: demo }),
    prisma.rfq.count({ where: { simulated: true } }),
    prisma.sellerProfile.count({ where: demo }),
    prisma.organization.count({ where: { ...demo, type: "BUYER" } }),
    prisma.rfqUnlock.count({ where: demo }),
    prisma.quote.count({ where: { ...demo, submittedAt: { not: null } } }),
    prisma.rfq.count({ where: { ...demo, selectedQuoteId: { not: null } } }),
    prisma.dispute.count({ where: { unlock: { isDemo: true } } }),
    prisma.rfqUnlock.aggregate({ where: demo, _sum: { priceMinor: true } }),
    prisma.platformSetting.findUnique({ where: { key: "demo.version" } }),
  ]);
  return (
    <>
      <PageHeader eyebrow="Demo mode" title="Demo control center" description="Drive the fictional marketplace for presentations. Every action runs through the real services against isDemo records — no real email, SMS or payments." />
      <Alert tone="warning" className="mb-6" title="SIMULATED DEMO METRICS — NOT ACTUAL BUSINESS PERFORMANCE">
        Counts below describe fictional demo data only. Production reporting excludes every isDemo record.
        {!version && " The demo baseline marker is missing — run a full reset to rebuild the current baseline."}
      </Alert>
      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Demo RFQs" value={rfqs} hint={`${simulated} generated by the simulator`} href="/admin/rfqs" />
        <StatCard label="Demo manufacturers / buyers" value={`${sellers} / ${buyers}`} href="/admin/sellers" />
        <StatCard label="Simulated unlocks" value={unlocks} hint={`${formatMoney(unlockSum._sum.priceMinor ?? 0, "USD")} in demo credits — not revenue`} href="/admin/unlocks" />
        <StatCard label="Quotes · selections · claims" value={`${quotes} · ${selected} · ${claims}`} href="/admin/quotes" />
      </div>
      <div className="mb-6 flex flex-wrap items-center gap-2 text-sm">
        <span className="text-muted">Switch persona:</span>
        <Link className="rounded-full border border-line px-3 py-1 hover:border-electric" href="/demo/buyer">Buyer · {DEMO_ACCOUNTS.buyer.name}</Link>
        <Link className="rounded-full border border-line px-3 py-1 hover:border-electric" href="/demo/manufacturer">Manufacturer · {DEMO_ACCOUNTS.seller.company}</Link>
        <Link className="rounded-full border border-line px-3 py-1 hover:border-electric" href="/demo/admin">Admin · {DEMO_ACCOUNTS.admin.name}</Link>
        <span className="mx-2 text-line">|</span>
        <Link className="font-semibold text-electric hover:underline" href="/admin/analytics?demo=1">Demo analytics</Link>
        <Link className="font-semibold text-electric hover:underline" href="/live">Live board</Link>
      </div>
      <DemoControlPanel settings={settings} presets={Object.fromEntries(Object.entries(DEMO_PRESETS).map(([k, v]) => [k, { label: v.label }]))} scenarios={SCENARIOS} />
    </>
  );
}
